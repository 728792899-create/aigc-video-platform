def set_cn(run, font="宋体"):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font)

def h(text, level, size, font="黑体"):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)
    r = p.add_run(text)
    r.font.size = Pt(size); r.font.bold = True
    set_cn(r, font)
    return p

def para(text, indent=True, bold_lead=None):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(24) if indent else Pt(0)
    if bold_lead:
        rb = p.add_run(bold_lead); rb.font.bold = True; rb.font.size = Pt(12); set_cn(rb)
    r = p.add_run(text); r.font.size = Pt(12); set_cn(r)
    return p

def caption(text):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(4); p.paragraph_format.space_after = Pt(4)
    r = p.add_run(text); r.font.size = Pt(10.5); r.font.bold = True; set_cn(r)

def shade(cell, color):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd"); sh.set(qn("w:val"), "clear")
    sh.set(qn("w:fill"), color); tcPr.append(sh)

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hcells = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hcells[i].text = ""
        p = hcells[i].paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(htxt); r.font.bold = True; r.font.size = Pt(10.5); set_cn(r)
        shade(hcells[i], "D9E2F3")
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            r = p.add_run(str(val)); r.font.size = Pt(10.5); set_cn(r)
    if widths:
        for ri in range(len(t.rows)):
            for ci, w in enumerate(widths):
                t.rows[ri].cells[ci].width = Cm(w)
    return t

